package com.vetcare.pacientes.model;

import java.time.Instant;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

@Document("mascotas")
public class Mascota {

    @Id
    private String id;
    private String nombre;
    private String especie;
    private String raza;
    private SexoMascota sexo;
    private LocalDate fechaNacimiento;
    private double pesoKg;
    @Indexed
    private String propietarioId;
    private EstadoMascota estado = EstadoMascota.ACTIVA;
    private LocalDate fechaFallecimiento;
    private List<String> alergias = new ArrayList<>();
    private List<String> condicionesCronicas = new ArrayList<>();
    private List<TransferenciaMascota> transferencias = new ArrayList<>();
    private Instant creadoEn = Instant.now();

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public String getEspecie() {
        return especie;
    }

    public void setEspecie(String especie) {
        this.especie = especie;
    }

    public String getRaza() {
        return raza;
    }

    public void setRaza(String raza) {
        this.raza = raza;
    }

    public SexoMascota getSexo() {
        return sexo;
    }

    public void setSexo(SexoMascota sexo) {
        this.sexo = sexo;
    }

    public LocalDate getFechaNacimiento() {
        return fechaNacimiento;
    }

    public void setFechaNacimiento(LocalDate fechaNacimiento) {
        this.fechaNacimiento = fechaNacimiento;
    }

    public double getPesoKg() {
        return pesoKg;
    }

    public void setPesoKg(double pesoKg) {
        this.pesoKg = pesoKg;
    }

    public String getPropietarioId() {
        return propietarioId;
    }

    public void setPropietarioId(String propietarioId) {
        this.propietarioId = propietarioId;
    }

    public EstadoMascota getEstado() {
        return estado;
    }

    public void setEstado(EstadoMascota estado) {
        this.estado = estado;
    }

    public LocalDate getFechaFallecimiento() {
        return fechaFallecimiento;
    }

    public void setFechaFallecimiento(LocalDate fechaFallecimiento) {
        this.fechaFallecimiento = fechaFallecimiento;
    }

    public List<String> getAlergias() {
        return alergias;
    }

    public void setAlergias(List<String> alergias) {
        this.alergias = alergias;
    }

    public List<String> getCondicionesCronicas() {
        return condicionesCronicas;
    }

    public void setCondicionesCronicas(List<String> condicionesCronicas) {
        this.condicionesCronicas = condicionesCronicas;
    }

    public List<TransferenciaMascota> getTransferencias() {
        return transferencias;
    }

    public void setTransferencias(List<TransferenciaMascota> transferencias) {
        this.transferencias = transferencias;
    }

    public Instant getCreadoEn() {
        return creadoEn;
    }

    public void setCreadoEn(Instant creadoEn) {
        this.creadoEn = creadoEn;
    }
}
